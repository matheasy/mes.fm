#!/usr/bin/env python3
"""Writes tool_apps_src/bmi-kids/data.js: the CDC 2000 BMI-for-age LMS parameters (ages 2-20 years, boys and girls), used by the
BMI Calculator for Kids and Teens (mes.fm/bmi-calculator-kids). Public domain (US government work).

Source: the CDC reference file behind CDC's SAS growth-chart program (CDCref_d.csv, columns _AGEMOS1 / _LBMI1 / _MBMI1 / _SBMI1, the same
values as CDC's bmiagerev.csv). cdc.gov answers scripts with 403, so by default the copy kept in the growthcleanr project (carriedaymont/growthcleanr,
inst/extdata/CDCref_d.csv.gz) is downloaded; --cache FILE uses a local CDCref_d.csv or .csv.gz instead (for example one saved from cdc.gov by hand).
Rows: one per month of age (23.5, 24.5, ... 239.5 months, plus 240.0 from the last row's _AGEMOS2 columns).
Dry-runs by default; --apply writes."""
import sys, os, csv, gzip, io, json, urllib.request
ROOT = os.path.dirname(os.path.abspath(__file__))
URL = "https://raw.githubusercontent.com/carriedaymont/growthcleanr/main/inst/extdata/CDCref_d.csv.gz"
OUT = os.path.join(ROOT, "tool_apps_src", "bmi-kids", "data.js")


def load(cache):
    if cache:
        raw = open(cache, "rb").read()
    else:
        raw = urllib.request.urlopen(urllib.request.Request(URL, headers={"User-Agent": "mes.fm-build/1.0"}), timeout=30).read()
    if raw[:2] == b"\x1f\x8b":
        raw = gzip.decompress(raw)
    return list(csv.DictReader(io.StringIO(raw.decode("utf-8"))))


def main():
    apply = "--apply" in sys.argv
    cache = sys.argv[sys.argv.index("--cache") + 1] if "--cache" in sys.argv else None
    rows = [r for r in load(cache) if r["denom"] == "age" and r["_LBMI1"].strip()]
    data = {}
    for sexn, key in (("1", "m"), ("2", "f")):
        rs = sorted((r for r in rows if r["SEX"] == sexn), key=lambda r: float(r["_AGEMOS1"]))
        t = [[float(r["_AGEMOS1"]), round(float(r["_LBMI1"]), 7), round(float(r["_MBMI1"]), 6), round(float(r["_SBMI1"]), 7)] for r in rs]
        last = rs[-1]
        t.append([float(last["_AGEMOS2"]), round(float(last["_LBMI2"]), 7), round(float(last["_MBMI2"]), 6), round(float(last["_SBMI2"]), 7)])
        for a, b in zip(t, t[1:]):
            assert 0 < b[0] - a[0] <= 1 + 1e-9, (key, a[0], b[0])
        assert t[0][0] == 23.5 and t[-1][0] == 240.0, (t[0][0], t[-1][0])
        data[key] = t
        print(key, len(t), "rows; 24.5 mo:", t[1], " 240 mo:", t[-1])
    js = ("/* CDC 2000 BMI-for-age growth charts: LMS parameters by sex (m / f), one row per month of age [age in months, L, M, S], 23.5 to 240 months.\n"
          "   Public domain (CDC / NCHS). Generated by build_cdc_bmi_data.py from CDC's reference file CDCref_d.csv; do not edit. */\n"
          "var CDC_BMI = " + json.dumps(data, separators=(",", ":")) + ";\nif (typeof module !== 'undefined' && module.exports) module.exports = CDC_BMI;\n")
    print("data.js: %d bytes" % len(js))
    if apply:
        open(OUT, "w").write(js)
        print("written", OUT)
    else:
        print("dry run: pass --apply to write")


main()
