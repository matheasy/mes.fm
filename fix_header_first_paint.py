#!/usr/bin/env python3
"""First paint of the header and the card hubs (2026-11-01).

On mobile Brave mes.fm/tools sometimes painted for a moment with a broken logo (alt text "Math Easy Solutions logo"),
default grey buttons for the category chips, "New tools / Popular" as plain text and a column of bare icons. The page's
body paints while the parser waits on the blocking jQuery <script> near the end of <body> (Brave can be slow on
ajax.googleapis.com), and at that moment:

  1. the header logo had class="lazyload" + data-src only, so it has no src until lazysizes (async) runs;
  2. the chip / section / mini-pill CSS was injected by the deferred main_js/hub-filter.js and main_js/newest.js.

Fixes:
  * every `<img id="logo" class="logo lazyload" data-src=...>` gets a real `src` (it is always above the fold, so lazy
    loading only ever delayed it) -- every page and every generator / template that emits it;
  * main_js/hub-filter.css and main_js/mini-pills.css are written from the CSS strings inside hub-filter.js / newest.js
    (evaluated with node, so they are the same rules) and linked in the <head> of every page that loads those scripts.
    The scripts still inject their own copy (identical rules), so editing the JS stays enough to change the look; re-run
    this script afterwards to refresh the static copies used for first paint.

Files that already have uncommitted changes (another session's work) are skipped and listed, unless --include-dirty.
Idempotent; dry-runs by default (-v lists files), --apply writes.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SITE = ROOT / "mes.fm"
APPLY = "--apply" in sys.argv
VERBOSE = "-v" in sys.argv
INCLUDE_DIRTY = "--include-dirty" in sys.argv

CSS_SOURCES = [  # (script, static css file, link id)
    ("main_js/hub-filter.js", "main_js/hub-filter.css", "mes-hubf-static"),
    ("main_js/newest.js", "main_js/mini-pills.css", "mes-mini-static"),
]
CSS_V = "1"

NODE_EVAL = r"""
const fs = require('fs'); const src = fs.readFileSync(process.argv[1], 'utf8');
const i = src.indexOf('css.textContent =');
if (i < 0) { console.error('no css.textContent'); process.exit(2); }
let j = i + 'css.textContent ='.length, depth = 0, q = null;
for (; j < src.length; j++) {          // scan to the ';' that ends the expression (outside strings / brackets)
  const c = src[j];
  if (q) { if (c === '\\') { j++; continue; } if (c === q) q = null; continue; }
  if (c === '"' || c === "'" || c === '`') { q = c; continue; }
  if (c === '/' && src[j + 1] === '*') { j = src.indexOf('*/', j) + 1; continue; }
  if (c === '(' || c === '[') depth++; else if (c === ')' || c === ']') depth--;
  else if (c === ';' && depth === 0) break;
}
process.stdout.write(eval(src.slice(i + 'css.textContent ='.length, j)));
"""

LOGO_RE = re.compile(r'<img\b[^>]*\bid="logo" class="logo lazyload"[^>]*>')


def dirty_paths():
    out = subprocess.run(["git", "status", "--porcelain"], cwd=ROOT, capture_output=True, text=True).stdout
    return {ROOT / line[3:].strip() for line in out.splitlines() if line.strip()}


def fix_logo(text):
    def one(m):
        tag = m.group(0).replace('class="logo lazyload"', 'class="logo"')
        return tag.replace(" data-src=", " src=", 1)
    return LOGO_RE.sub(one, text)


def add_links(text):
    for js, css, lid in CSS_SOURCES:
        if ("/" + js) not in text and ('"' + js) not in text:
            continue
        if ('id="%s"' % lid) in text:
            continue
        link = '<link rel="stylesheet" id="%s" href="/%s?v=%s">' % (lid, css, CSS_V)
        if "</head>" not in text:
            continue
        text = text.replace("</head>", link + "</head>", 1)
    return text


def main():
    changed = {}
    for js, css, lid in CSS_SOURCES:
        rules = subprocess.run(["node", "-e", NODE_EVAL, str(SITE / js)], capture_output=True, text=True, check=True).stdout
        head = "/* Generated by fix_header_first_paint.py from %s (same rules; linked in <head> for first paint). */\n" % js
        new = head + rules + "\n"
        p = SITE / css
        if not p.exists() or p.read_text(encoding="utf-8") != new:
            changed[p] = new

    dirty = set() if INCLUDE_DIRTY else dirty_paths()
    skipped = []
    files = [p for p in SITE.rglob("*.html") if "_http" not in str(p) and "node_modules" not in str(p)]
    files += list(SITE.glob("*/build.mjs")) + [ROOT / "tool_page_template.html", ROOT / "build_links_page.py",
                                                ROOT / "hive_mirror_template.html", ROOT / "math_qa_mirror_template.html"]
    n_logo = n_link = 0
    for p in files:
        if not p.exists():
            continue
        old = p.read_text(encoding="utf-8", errors="surrogateescape")
        new = fix_logo(old)
        a = new != old
        if p.suffix == ".html":
            new2 = add_links(new)
            b = new2 != new
            new = new2
        else:
            b = False
        if new == old:
            continue
        if p in dirty:
            skipped.append(p)
            continue
        n_logo += a
        n_link += b
        changed[p] = new
        if VERBOSE:
            print(("logo " if a else "     ") + ("css " if b else "    ") + str(p.relative_to(ROOT)))
    print("%d files to change (%d logo, %d css link), %d css files" % (
        len(changed), n_logo, n_link, sum(1 for p in changed if p.suffix == ".css")))
    for p in skipped:
        print("SKIPPED (uncommitted changes): %s" % p.relative_to(ROOT))
    if APPLY:
        for p, t in changed.items():
            p.write_text(t, encoding="utf-8", errors="surrogateescape")
        print("written")
    else:
        print("dry run; --apply writes")


if __name__ == "__main__":
    main()
