#!/usr/bin/env python3
"""Writes tool_apps_src/baby-growth/data.js: the WHO Child Growth Standards LMS tables (0-5 years, one row per 7 days) for weight-for-age,
length/height-for-age and head-circumference-for-age, boys and girls. Source: the 'expanded tables' workbooks on who.int
(https://www.who.int/tools/child-growth-standards/standards). Downloads the six .xlsx files (stdlib only, no openpyxl) unless they are in --cache DIR.
Dry-runs by default; --apply writes."""
import sys, os, re, json, zipfile, urllib.request
from xml.etree import ElementTree as ET
ROOT = os.path.dirname(os.path.abspath(__file__))
B = "https://cdn.who.int/media/docs/default-source/child-growth/child-growth-standards/indicators/"
FILES = {"wfa": "weight-for-age/expanded-tables/wfa-%s-zscore-expanded-tables.xlsx", "lhfa": "length-height-for-age/expandable-tables/lhfa-%s-zscore-expanded-tables.xlsx", "hcfa": "head-circumference-for-age/expanded-tables/hcfa-%s-zscore-expanded-tables.xlsx"}
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
def rows(path):
    z = zipfile.ZipFile(path); ss = []
    if "xl/sharedStrings.xml" in z.namelist():
        for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS): ss.append("".join(t.text or "" for t in si.iter("{%s}t" % NS["m"])))
    out = []
    for r in ET.fromstring(z.read("xl/worksheets/sheet1.xml")).iter("{%s}row" % NS["m"]):
        row = []
        for c in r.findall("m:c", NS):
            v = c.find("m:v", NS); row.append(None if v is None else (ss[int(v.text)] if c.get("t") == "s" else float(v.text)))
        out.append(row)
    return out
def main():
    apply = "--apply" in sys.argv; cache = sys.argv[sys.argv.index("--cache") + 1] if "--cache" in sys.argv else None
    data = {}
    for k, tpl in FILES.items():
        data[k] = {}
        for sx, name in (("m", "boys"), ("f", "girls")):
            fn = tpl % name; local = os.path.join(cache, os.path.basename(fn)) if cache else None
            if local and os.path.exists(local): path = local
            else:
                path = "/tmp/who-%s-%s.xlsx" % (k, name); urllib.request.urlretrieve(B + fn, path)
            rs = rows(path); hdr = rs[0]; assert hdr[:4] == ["Day", "L", "M", "S"], hdr
            sel = [r for r in rs[1:] if r[0] is not None and int(r[0]) % 7 == 0 and r[0] <= 1855]
            data[k][sx] = [[round(r[1], 4), round(r[2], 4), round(r[3], 5)] for r in sel]
            print(k, name, len(sel), "rows, day 0:", sel[0][:4])
    js = "/* WHO Child Growth Standards (2006) LMS parameters, 0-5 years, one row per 7 days (row i = day 7*i). Generated by build_growth_data.py; do not edit. */\nvar WHO_LMS = " + json.dumps(data, separators=(",", ":")) + ";\nif (typeof module !== 'undefined' && module.exports) module.exports = WHO_LMS;\n"
    print("data.js: %d bytes" % len(js))
    if apply:
        open(os.path.join(ROOT, "tool_apps_src", "baby-growth", "data.js"), "w").write(js); print("written")
    else: print("dry run: pass --apply to write")
main()
