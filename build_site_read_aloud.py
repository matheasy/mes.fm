#!/usr/bin/env python3
"""Builds mes.fm/main_js/site-read-aloud.js: the MES Read Aloud engine for mes.fm's own pages (the speaker button in the header controls).

It is the browser extension's code (mes.fm/read-aloud/extension/shared.js + reader.js) plus the Speed Reader's lib.js, wrapped in one function
that gives the reader a small `chrome` stand-in backed by localStorage (setups -> `mes-readaloud:v1`, player position -> `mes-readaloud:ui`), so
there is a single source of truth for the reading / highlighting code. It is only downloaded when someone clicks the speaker button
(main_js/site-search.js adds the button and loads this file on demand).
Dry-runs by default; --apply writes.  Re-run after changing the extension's reader.js / shared.js or the Speed Reader's lib.js.
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent
OUT = REPO / "mes.fm" / "main_js" / "site-read-aloud.js"
EXT = REPO / "mes.fm" / "read-aloud" / "extension"
SRLIB = REPO / "tool_apps_src" / "speedreader" / "lib.js"

HEAD = '''/* MES Read Aloud for mes.fm pages. GENERATED by build_site_read_aloud.py from the browser extension's reader + the Speed Reader's lib: do not edit.
   Loaded on demand by main_js/site-search.js when the speaker button in the header controls is clicked. */
(function () {
  "use strict";
  if (window.MESReadAloud) return;
  window.__mesraSite = true;                                  // the player hides its settings gear (no options page here)
  window.__mesraRoots = [".page-content", "#main-content"];   // where the text to read lives on mes.fm pages

  /* a tiny stand-in for chrome.storage.sync / .local (+ onChanged) and chrome.runtime.onMessage, on top of localStorage */
  var listeners = [], msgListener = null;
  function area(name, key) {
    return {
      get: function (k, cb) { var o = {}; try { var v = localStorage.getItem(key); if (v) o[k] = JSON.parse(v); } catch (e) { /* ignore */ } setTimeout(function () { cb(o); }, 0); },
      set: function (o, cb) {
        var ch = {};
        Object.keys(o).forEach(function (k) { ch[k] = { newValue: o[k] }; try { localStorage.setItem(key, JSON.stringify(o[k])); } catch (e) { /* ignore */ } });
        listeners.forEach(function (f) { try { f(ch, name); } catch (e) { /* ignore */ } });
        if (cb) cb();
      }
    };
  }
  var chrome = {
    storage: { sync: area("sync", "mes-readaloud:v1"), local: area("local", "mes-readaloud:ui"), onChanged: { addListener: function (f) { listeners.push(f); } } },
    runtime: { onMessage: { addListener: function (f) { msgListener = f; } }, sendMessage: function () {} }
  };
'''
TAIL = '''
  window.MESReadAloud = {
    // the speaker button: start reading (the selection, else the page from where you clicked), or pause / resume if a player is open
    toggle: function () { if (msgListener) msgListener({ mesra: "toggle" }, {}, function () {}); },
    stop: function () { if (msgListener) msgListener({ mesra: "stop" }, {}, function () {}); }
  };
})();
'''


def main():
    srlib = SRLIB.read_text(encoding="utf-8")
    parts = [HEAD, "\n  /* ---- Speed Reader lib (tokenizer, sentence chunks, voices) ---- */\n", srlib, "\n  window.SRLib = SRLib;\n",
             "\n  /* ---- setups + page text map (extension/shared.js) ---- */\n", (EXT / "shared.js").read_text(encoding="utf-8"),
             "\n  /* ---- the reader (extension/reader.js) ---- */\n", (EXT / "reader.js").read_text(encoding="utf-8"), TAIL]
    out = "".join(parts)
    print("site-read-aloud.js: %d bytes (%d KB gzipped is about a third of that)" % (len(out.encode("utf-8")), len(out) // 3000))
    if "--apply" not in sys.argv:
        print("dry run: pass --apply to write", OUT.relative_to(REPO))
        return
    OUT.write_text(out, encoding="utf-8")
    print("wrote", OUT.relative_to(REPO))


if __name__ == "__main__":
    main()
